export function upgradeSet(save) {
  return new Set(save.upgrades || []);
}

export function playerMods(save) {
  const up = upgradeSet(save);
  return {
    maxArmor: up.has('armor') ? 140 : 100,
    speed: up.has('boots') ? 1.1 : 1,
    grenades: up.has('pouch') ? 5 : 3,
    focusCooldown: up.has('focus') ? 13 : 19,
    suppressed: up.has('suppressor'),
    armorPlates: up.has('armor'),
  };
}

export function resolveWeapon(id, save) {
  const base = WEAPONS[id] || WEAPONS.vector;
  const up = upgradeSet(save);
  const w = { ...base };
  if (up.has('ap')) {
    w.dmg = base.dmg * 1.08;
    w.pen = base.pen + 1;
  }
  if (up.has('optic')) w.spread = base.spread * 0.82;
  if (up.has('mag')) w.mag = Math.round(base.mag * 1.5);
  if (up.has('suppressor')) {
    w.suppressed = true;
    w.sound = 'suppressed';
  }
  w.reserve = Math.round(base.reserve * (up.has('mag') ? 1.25 : 1));
  return w;
}

export function threatDots(level) {
  return '◆'.repeat(level) + '◇'.repeat(Math.max(0, 6 - level));
}
